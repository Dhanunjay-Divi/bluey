export function previewWorkspaceForScenario(workspace: JobsWorkspace, scenario: string): JobsWorkspace {
  if (scenario === "onboarding") {
    return {
      ...workspace,
      profile: {
        ...workspace.profile,
        onboarding_step: 0,
        onboarding_complete: false,
      },
      tracks: [],
      matches: [],
      applications: [],
      browser_sessions: [],
      interventions: [],
    };
  }
  if (scenario === "many-matches") {
    const matches = Array.from({ length: 125 }, (_, index) => {
      const template = workspace.matches[index % workspace.matches.length];
      const candidateLead = index % 4 === 0;
      const eligibility = template.eligibility ?? betaEligibility();
      return {
        ...template,
        id: `volume-job-${index + 1}`,
        canonical_key: `volume-job-${index + 1}`,
        external_id: `volume-${index + 1}`,
        company: `${template.company} ${index + 1}`,
        title: index % 3 === 0 ? `Senior Product Engineer ${index + 1}` : template.title,
        source: candidateLead ? "curated_feed:preview-volume" : template.source,
        canonical_url: `https://example.com/jobs/volume-${index + 1}`,
        track_id: workspace.tracks[index % workspace.tracks.length].id,
        match_score: 70 + (index % 26),
        posted_at_ms: now - (index % 10) * 86_400_000,
        last_verified_at_ms: candidateLead ? undefined : now - (index % 60) * 60_000,
        availability_status: candidateLead ? "unknown" as const : "active" as const,
        eligibility: candidateLead ? {
          ...eligibility,
          can_prepare: false,
          can_auto_submit: false,
          can_queue_local: false,
          can_queue_cloud: false,
        } : eligibility,
      };
    });
    return {
      ...workspace,
      matches,
      discovery_sources: [
        ...workspace.discovery_sources,
        {
          id: "source-curated-preview",
          provider: "curated_feed",
          config: { company: "Curated career feeds" },
          status: "active",
          health: "healthy",
          last_success_at_ms: now - 90_000,
        },
      ],
    };
  }
  if (scenario !== "final-review") return workspace;

  const title = "Review the Greenhouse application";
  const detail = "Review every employer-facing field and document in the preserved form, then approve submission.";
  const takeoverUrl = "https://jobs-browser.bluey.sh/sessions/browser-final-review";
  return {
    ...workspace,
    browser_sessions: [{
      id: "browser-final-review",
      runner: "cloud",
      status: "needs_input",
      current_company: "Meridian Financial",
      current_step: "Final application review",
      application_id: "app-2",
      takeover_url: takeoverUrl,
      created_at_ms: now - 900_000,
      updated_at_ms: now - 30_000,
    }],
    interventions: [{
      id: "intervention-final-review",
      application_id: "app-2",
      kind: "browser_takeover",
      status: "open",
      title,
      detail,
      choices: [],
      resolution_kind: "browser_takeover",
      resume_after_resolution: true,
      provider: "",
      provider_message_id: "",
      metadata: {
        receipt: {
          status: "needs_input",
          issues: [],
          intervention: {
            kind: "browser_takeover",
            title,
            detail,
            takeoverUrl,
            resolution: { kind: "browser_takeover", resumeAfter: true },
          },
        },
      },
      created_at_ms: now - 30_000,
    }],
  };
}
