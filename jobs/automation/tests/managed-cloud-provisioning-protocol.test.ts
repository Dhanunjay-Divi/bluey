describe("managed-cloud provisioning closed dependency probes", () => {
  it.each(PROBES)("roundtrips the closed $kind arm without conferring authority", (value) => {
    const parsed = parseManagedCloudDependencyProbe(value);
    expect(parsed).toEqual(value);
    expect(Object.isFrozen(parsed)).toBe(true);
    expect(parseProvisioningCanonicalJsonBytes(provisioningCanonicalJsonBytes(parsed))).toEqual(value);
    for (const key of Object.keys(value)) {
      const missing = { ...value } as Record<string, unknown>;
      delete missing[key];
      expect(() => parseManagedCloudDependencyProbe(missing)).toThrow();
    }
    expect(() => parseManagedCloudDependencyProbe({ ...value, checks: [] })).toThrow();
    expect(() => parseManagedCloudDependencyProbe({ ...value, version: "1" })).toThrow();
  });

  it("retains typed unavailable and stopped observations rather than inventing health", () => {
    for (const [kind, field] of [["workflow_gateway", "temporalNamespace"], ["workflow_worker", "temporalNamespace"],
      ["workflow_command_dispatcher", "gatewayControl"], ["workflow_cleanup_dispatcher", "gatewayControl"],
      ["original_source_verifier", "bootStartup"], ["managed_runner", "volumeBinding"]] as const) {
      const value = PROBES.find((probe) => probe.kind === kind)!;
      expect(parseManagedCloudDependencyProbe({ ...value, [field]: null })).toHaveProperty(field, null);
    }
    const stopped = { version: 1, kind: "discovery_worker", loopState: "stopped", controlProgress: "stale" };
    expect(parseManagedCloudDependencyProbe(stopped)).toEqual(stopped);
    expect(() => parseManagedCloudDependencyProbe({ ...stopped, controlProgress: "fresh" })).toThrow();
    expect(() => parseManagedCloudDependencyProbe({ ...stopped, kind: "arbitrary_check" })).toThrow();
  });

  it("requires every closed nested reference field including the gateway observation", () => {
    const cases = [
      { outer: PROBES[3]!, field: "temporalNamespace", nested: temporalNamespace() },
      { outer: PROBES[1]!, field: "gatewayControl", nested: gatewayControl() },
      { outer: PROBES[7]!, field: "bootStartup", nested: bootStartup() },
      { outer: PROBES[8]!, field: "volumeBinding", nested: volumeBinding() },
    ];
    for (const { outer, field, nested } of cases) {
      for (const key of Object.keys(nested)) {
        const missing = { ...nested } as Record<string, unknown>;
        delete missing[key];
        expect(() => parseManagedCloudDependencyProbe({ ...outer, [field]: missing })).toThrow();
      }
      expect(() => parseManagedCloudDependencyProbe({ ...outer, [field]: { ...nested, extra: null } })).toThrow();
    }
  });

  it("rejects numeric aliases, URI components, noncanonical ports and unsupported IPv6", () => {
    for (const authority of ["127.1:7233", "2130706433:7233", "0177.0.0.1:7233", "0x7f000001:7233",
      "a.123:7233", "a.0x7f:7233", "a.0x:7233", "temporal.example.test.:7233",
      "Temporal.example.test:7233", "a..test:7233", "-a.test:7233", "a-.test:7233", "a".repeat(64) + ".test:7233",
      "temporal.test:0", "temporal.test:07233", "temporal.test:65536", "temporal.test", "user@temporal.test:7233",
      "https://temporal.test:7233", "temporal.test:7233/path", "temporal.test:7233?query", "[::1]:7233"]) {
      expect(() => parseManagedCloudDependencyProbe({ ...PROBES[3], temporalNamespace: { ...temporalNamespace(), authority } }))
        .toThrow();
    }
    for (const authority of ["127.0.0.1:7233", "0.0.0.0:1", "255.255.255.255:65535", "temporal:7233", "foo.0xyz:7233"]) {
      expect(parseManagedCloudDependencyProbe({ ...PROBES[3], temporalNamespace: { ...temporalNamespace(), authority } }))
        .toHaveProperty("temporalNamespace.authority", authority);
    }
  });

  it("binds typed transports and bounds NFC namespace bytes and safe integers", () => {
    const base = { ...PROBES[3], temporalNamespace: temporalNamespace() };
    for (const namespace of ["", " space", "space ", "e\u0301", "\ud800", "\ufffd", "a\u0085b", "é".repeat(121)]) {
      expect(() => parseManagedCloudDependencyProbe({ ...base, temporalNamespace: { ...temporalNamespace(), namespace } }))
        .toThrow();
    }
    expect(parseManagedCloudDependencyProbe({ ...base, temporalNamespace: { ...temporalNamespace(), namespace: "é".repeat(120) } }))
      .toHaveProperty("temporalNamespace.namespace", "é".repeat(120));
    expect(() => parseManagedCloudDependencyProbe({ ...base, temporalNamespace: { ...temporalNamespace(), transport: "https" } }))
      .toThrow();
    expect(() => parseManagedCloudDependencyProbe({ ...base, temporalNamespace: { ...temporalNamespace(), namespaceId: "é".repeat(65) } }))
      .toThrow();
    for (const instanceEpoch of [0, -1, 1.5, Number.MAX_SAFE_INTEGER + 1, "1"]) {
      expect(() => parseManagedCloudDependencyProbe({ ...PROBES[1], gatewayControl: { ...gatewayControl(), instanceEpoch } }))
        .toThrow();
    }
    expect(() => parseManagedCloudDependencyProbe({ ...PROBES[1], gatewayControl: { ...gatewayControl(), transport: "tls" } }))
      .toThrow();
  });

  it("uses canonical native volume/process tokens and the existing runner grant grammar", () => {
    for (const volumeId of ["volume-1", TOKEN + "=", "A".repeat(42) + "B"]) {
      expect(() => parseManagedCloudDependencyProbe({ ...PROBES[8], volumeBinding: { ...volumeBinding(), volumeId } }))
        .toThrow();
    }
    for (const runtimeGrantId of ["", "-grant", "g/1", "g".repeat(129)]) {
      expect(() => parseManagedCloudDependencyProbe({ ...PROBES[8], volumeBinding: { ...volumeBinding(), runtimeGrantId } }))
        .toThrow();
    }
    expect(parseManagedCloudDependencyProbe({ ...PROBES[8], volumeBinding: { ...volumeBinding(), runtimeGrantId: "g._:+-1" } }))
      .toHaveProperty("volumeBinding.runtimeGrantId", "g._:+-1");
    for (const field of ["bootId", "startupRequestId"] as const) {
      for (const value of ["a".repeat(14) + ":/.-_a", "a".repeat(122) + ":/.-_a"]) {
        expect(parseManagedCloudDependencyProbe({ ...PROBES[7], bootStartup: { ...bootStartup(), [field]: value } }))
          .toHaveProperty(`bootStartup.${field}`, value);
      }
      for (const value of ["a".repeat(19), "a".repeat(129), "a".repeat(19) + "+",
        "a".repeat(19) + " ", "a".repeat(19) + "%"]) {
        expect(() => parseManagedCloudDependencyProbe({ ...PROBES[7], bootStartup: { ...bootStartup(), [field]: value } }))
          .toThrow();
      }
    }
  });
});

