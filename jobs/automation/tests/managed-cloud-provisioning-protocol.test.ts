function dependency(binding: typeof PROD | typeof SYNTHETIC) {
  return { role: "managed_runner" as const, activationSha256: "a".repeat(64),
    manifestSha256: "b".repeat(64), componentId: "jobs-runner", artifactSha256: "d".repeat(64),
    taskQueueSha256: "e".repeat(64), failureConverterSha256: "f".repeat(64), authorityBinding: binding };
}

describe("managed-cloud provisioning pure foundation", () => {
  it.each(VECTORS)("pins independent $size-byte binding/session/dependency vectors", (vector) => {
    // Literal outputs were independently checked with Python/OpenSSL and Node,
    // not generated by the implementation under test. These are synthetic keys.
    const parsed = parseManagedCloudAuthorityBinding(vector.binding);
    const bytes = provisioningCanonicalJsonBytes(parsed);
    expect(Buffer.from(bytes).toString("utf8")).toBe(vector.canonical);
    expect(bytes.byteLength).toBe(vector.size);
    expect(createHash("sha256").update(bytes).digest("hex")).toBe(vector.sha256);
    expect(parseProvisioningCanonicalJsonBytes(bytes)).toEqual(vector.binding);
    expect(parseManagedCloudAuthorityBindingBytes(bytes)).toEqual(vector.binding);
    expect(deriveManagedCloudProvisioningSessionToken(TOKEN, "g".repeat(20), "r".repeat(20), parsed))
      .toBe(vector.session);
    expect(deriveManagedCloudProvisioningDependencyEvidenceSha256(dependency(vector.binding)))
      .toBe(vector.dependency);
    expect(Object.isFrozen(parsed)).toBe(true);
  });

  it("rejects missing, unknown, cross-purpose and malformed binding fields", () => {
    const { contextSha256: _context, ...missing } = PROD;
    for (const value of [missing, { ...PROD, extra: false }, { ...PROD, authorityKind: "activation_v3" },
      { ...PROD, contextSha256: "c".repeat(64) }, { ...SYNTHETIC, contextSha256: null },
      { ...SYNTHETIC, contextSha256: "C".repeat(64) }, { ...PROD, purpose: "staging" },
      { ...PROD, queueGenerationId: "q".repeat(19) }, { ...PROD, queueGenerationId: "q".repeat(129) },
      { ...PROD, queueGenerationId: "q".repeat(19) + "." }, { ...PROD, queueGenerationId: "é".repeat(20) }]) {
      expect(() => parseManagedCloudAuthorityBinding(value)).toThrow("protocol is invalid");
    }
    expect(parseManagedCloudAuthorityBinding({ ...SYNTHETIC, contextSha256: "0".repeat(64) }))
      .toMatchObject({ contextSha256: "0".repeat(64) });
  });

  it("requires canonical duplicate-free bytes with exactly one LF", () => {
    for (const raw of ["{}", "{}\n\n", " {}\n", '{"a":1,"a":1}\n', '{"b":2,"a":1}\n',
      '{"a":1.0}\n', '{"a":1e0}\n', '{"a":-0}\n', '{"a":"\\u0061"}\n',
      '{"a":9007199254740992}\n', '{"a":NaN}\n', '{"a":"\\ud800"}\n']) {
      expect(() => parseProvisioningCanonicalJsonBytes(Buffer.from(raw))).toThrow("protocol is invalid");
    }
    expect(() => parseProvisioningCanonicalJsonBytes(Buffer.from([0xff, 0x0a])))
      .toThrow("protocol is invalid");
    expect(() => parseProvisioningCanonicalJsonBytes(Buffer.alloc(64 * 1024 + 1)))
      .toThrow("protocol is invalid");
  });

  it("bounds canonical output, depth and unsafe input values without invoking accessors", () => {
    let calls = 0;
    const accessor = Object.defineProperty({}, "value", { enumerable: true, get: () => { calls += 1; return 1; } });
    let nested: unknown = null;
    for (let index = 0; index < 18; index += 1) nested = { nested };
    for (const value of [accessor, Object.assign({}, { [Symbol("hidden")]: 1 }), new Date(0), undefined,
      Number.NaN, Number.POSITIVE_INFINITY, -0, 0.5, Number.MAX_SAFE_INTEGER + 1,
      "\ud800", "\ufffd", "x".repeat(64 * 1024), nested, new Array(2)]) {
      expect(() => provisioningCanonicalJsonBytes(value)).toThrow("protocol is invalid");
    }
    expect(calls).toBe(0);
  });

  it("compares canonical structures rather than object identities or property insertion order", () => {
    expect(provisioningCanonicalEqual(PROD, { queueGenerationId: PROD.queueGenerationId,
      purpose: PROD.purpose, contextSha256: null, authorityKind: PROD.authorityKind })).toBe(true);
    expect(provisioningCanonicalEqual(PROD, SYNTHETIC)).toBe(false);
    expect(provisioningCanonicalEqual(PROD, { ...PROD, extra: null })).toBe(false);
  });

  it("rejects noncanonical, wrong-length and padded grant tokens and invalid route IDs", () => {
    for (const token of [TOKEN + "=", "A".repeat(42), "A".repeat(44), "A".repeat(42) + "B",
      "!" + "A".repeat(42)]) {
      expect(() => deriveManagedCloudProvisioningSessionToken(token, "g".repeat(20), "r".repeat(20), PROD))
        .toThrow("protocol is invalid");
    }
    expect(() => deriveManagedCloudProvisioningSessionToken(TOKEN, "short", "r".repeat(20), PROD)).toThrow();
    expect(() => deriveManagedCloudProvisioningSessionToken(TOKEN, "g".repeat(20), "r".repeat(129), PROD)).toThrow();
  });

  it("binds the session to the exact purpose, context, queue, grant and instance", () => {
    const base = deriveManagedCloudProvisioningSessionToken(TOKEN, "g".repeat(20), "r".repeat(20), SYNTHETIC);
    for (const binding of [PROD, { ...SYNTHETIC, contextSha256: "d".repeat(64) },
      { ...SYNTHETIC, queueGenerationId: "z".repeat(20) }]) {
      expect(deriveManagedCloudProvisioningSessionToken(TOKEN, "g".repeat(20), "r".repeat(20), binding))
        .not.toBe(base);
    }
    expect(deriveManagedCloudProvisioningSessionToken(TOKEN, "h".repeat(20), "r".repeat(20), SYNTHETIC))
      .not.toBe(base);
    expect(deriveManagedCloudProvisioningSessionToken(TOKEN, "g".repeat(20), "s".repeat(20), SYNTHETIC))
      .not.toBe(base);
  });

  it("rejects unknown dependency fields and role/component/hash drift", () => {
    const base = dependency(PROD);
    for (const input of [{ ...base, extra: 1 }, { ...base, role: "unknown" },
      { ...base, componentId: "jobs-api" }, { ...base, artifactSha256: "D".repeat(64) }]) {
      expect(() => deriveManagedCloudProvisioningDependencyEvidenceSha256(input as typeof base)).toThrow();
    }
    expect(deriveManagedCloudProvisioningDependencyEvidenceSha256({ ...base, artifactSha256: "0".repeat(64) }))
      .not.toBe(VECTORS[0].dependency);
  });

  it("keeps raw canonical decoding separate from value-shape parsing", () => {
    const duplicate = Buffer.from('{"authorityKind":"provisioning_v4","authorityKind":"provisioning_v4",' +
      '"contextSha256":null,"purpose":"production","queueGenerationId":"qqqqqqqqqqqqqqqqqqqq"}\n');
    expect(() => parseManagedCloudAuthorityBindingBytes(duplicate)).toThrow();
    // Once parsed, original byte facts are gone. Shape parsing does not claim
    // duplicate detection and does not require canonical HTTP serialization.
    expect(parseManagedCloudAuthorityBinding(JSON.parse(duplicate.toString("utf8")))).toEqual(PROD);
    expect(() => parseManagedCloudAuthorityBinding(Buffer.from(VECTORS[0].canonical))).toThrow();
    expect(() => parseManagedCloudAuthorityBindingBytes(Buffer.alloc(4097))).toThrow();
  });
});

